#!/usr/bin/env python3
"""Aggregate results/raw/*.json (+ security, bridge) into markdown tables and paper figures.

  python3 analyze.py   ->  results/RESULTS_TABLES.md, results/figures/*.png, results/summary.csv
"""
import csv, glob, json, os, re
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import ScalarFormatter, NullFormatter

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
FIG = os.path.join(RES, "figures")
os.makedirs(FIG, exist_ok=True)

# validated categorical palette (fixed order), text tokens, recessive grid
C = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300"]
MK = ["o", "s", "^", "D", "v", "P"]
INK, INK2, GRID = "#1f1f1e", "#5f5e5a", "#e4e3de"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": INK2, "axes.labelcolor": INK, "xtick.color": INK2,
                     "ytick.color": INK2, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
                     "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
                     "lines.linewidth": 2, "lines.markersize": 6, "savefig.dpi": 200})

R = {}
for f in glob.glob(os.path.join(RES, "raw", "*.json")):
    r = json.load(open(f)); R[r["name"]] = r


def get(prefix):
    """rounds whose name matches prefix_<tps>, sorted by target tps"""
    rows = [r for n, r in R.items() if re.fullmatch(re.escape(prefix) + r"_\d+(\.\d+)?", n)]
    return sorted(rows, key=lambda r: r["targetTps"])


def succ_rate(r): return 100.0 * r["succeeded"] / max(r["submitted"], 1)


def cpu(r, role): return r["resources"].get(role, {}).get("cpuAvgPct", 0.0)


def peak(rows):
    return max(rows, key=lambda r: r["throughput"]) if rows else None


def err_str(r):
    return ", ".join(f"{k} {v}" for k, v in sorted(r["errors"].items(), key=lambda kv: -kv[1])) or "-"


md = []
summary = []


def table(title, rows, extra_cols=()):
    if not rows: return
    md.append(f"\n### {title}\n")
    hdr = ["Offered (TPS)", "Send rate", "Throughput", "Success %", "Avg lat (s)", "p95 (s)", "Max (s)",
           "Host CPU %", "Peer CPU %", "CouchDB CPU %", "Orderer CPU %", "Peer RSS (MB)", "Peer net in (MB/s)", "Failures"]
    hdr += [c[0] for c in extra_cols]
    md.append("| " + " | ".join(hdr) + " |"); md.append("|" + "---|" * len(hdr))
    for r in rows:
        res = r["resources"]; p = res.get("peer", {})
        vals = [f"{r['targetTps']:g}", r["sendRate"], r["throughput"], f"{succ_rate(r):.1f}", r["latAvg"], r["latP95"], r["latMax"],
                res.get("host", {}).get("cpuAvgPct"), p.get("cpuAvgPct"), cpu(r, "couchdb"), cpu(r, "orderer"),
                p.get("memAvgMB"), p.get("netRxMBps"), err_str(r)]
        vals += [c[1](r) for c in extra_cols]
        md.append("| " + " | ".join("-" if v is None else str(v) for v in vals) + " |")
        summary.append({"name": r["name"], "tag": r["tag"], "workload": r["workload"], "channel": r["channel"],
                        "peers": r["network"]["totalPeers"], "orderers": r["network"]["orderers"],
                        "batch": f"{r['network']['batchTimeout']}/{r['network']['batchSize']}",
                        "policy": r.get("endorsementPolicy"), "offered": r["targetTps"], "throughput": r["throughput"],
                        "success_pct": round(succ_rate(r), 2), "lat_avg": r["latAvg"], "lat_p95": r["latP95"],
                        "host_cpu": res.get("host", {}).get("cpuAvgPct"), "host_mem_peak_mb": res.get("host", {}).get("memUsedPeakMB"),
                        "errors": err_str(r)})


def line(ax, rows, y, label, i, ls="-", end_label=True):
    if not rows: return
    xs = [r["targetTps"] for r in rows]; ys = [y(r) for r in rows]
    ax.plot(xs, ys, ls, color=C[i], marker=MK[i], label=label)
    if end_label: ax.annotate(label, (xs[-1], ys[-1]), xytext=(4, 0), textcoords="offset points", color=INK2, fontsize=8, va="center")


def save(fig, name):
    fig.tight_layout(); fig.savefig(os.path.join(FIG, name)); plt.close(fig)


md.append("# BlockAssist+ benchmark results (auto-generated by analyze.py)\n")

# ---------------------------------------------------------------- E1
WL = [("register", "RegisterInvestor (PDC)"), ("invest", "MakeInvestment (PDC)"),
      ("startup", "CreateStartup (PDC)"), ("token", "CreateTokenAccount (public)")]
md.append("\n## E1 - Offered load sweep, single channel (4 orgs x 1 peer, 1 Raft orderer, CouchDB, batch 2s/500)")
for wl, lab in WL: table(f"E1 {lab}", get(f"E1_single_{wl}"))
table("E1 read-only query (TokenContract:GetTokenAccount, evaluate)", get("E1_single_query"))
if get("E1_single_register"):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.8))
    mx = max(r["targetTps"] for wl, _ in WL for r in get(f"E1_single_{wl}") or [{"targetTps": 1}])
    ymax = 1.3 * max(r["throughput"] for wl, _ in WL for r in get(f"E1_single_{wl}"))
    a1.plot([20, ymax], [20, ymax], ":", color=INK2, lw=1); a1.annotate("ideal", (ymax * 0.55, ymax * 0.8), color=INK2, fontsize=8)
    for i, (wl, lab) in enumerate(WL):
        line(a1, get(f"E1_single_{wl}"), lambda r: r["throughput"], lab.split(" (")[0], i)
        line(a2, get(f"E1_single_{wl}"), lambda r: r["latAvg"], lab.split(" (")[0], i)
    a1.set_xscale("log"); a1.set_xlabel("Offered load (TPS, log)"); a1.set_ylabel("Committed throughput (TPS)"); a1.set_ylim(0, ymax)
    a1.set_title("Throughput vs offered load", color=INK, loc="left")
    a2.set_xscale("log"); a2.set_yscale("log"); a2.set_xlabel("Offered load (TPS, log)"); a2.set_ylabel("Average latency (s, log)")
    for ax_ in (a1, a2): ax_.xaxis.set_major_formatter(ScalarFormatter())
    a2.yaxis.set_major_formatter(ScalarFormatter()); a2.yaxis.set_minor_formatter(NullFormatter())
    a2.set_title("Latency vs offered load", color=INK, loc="left"); a1.legend(fontsize=8)
    save(fig, "fig_e1_throughput_latency.png")

# ---------------------------------------------------------------- E2
md.append("\n## E2 - Dual-channel architecture (same hardware, 4 peers, 1 orderer)")
mm = lambda r: f"{100.0 * r['errors'].get('ENDORSE_MISMATCH', 0) / max(r['submitted'], 1):.2f}"
for wl, lab in [("startup", "CreateStartup on governance channel, AND(Validator,Platform)"),
                ("invest", "MakeInvestment on investment channel, OR(any)"),
                ("token", "CreateTokenAccount on investment channel, OR(any)")]:
    table(f"E2 {lab}", get(f"E2_dual_{wl}"), [("Endorse-mismatch %", mm)])
table("E2 read-only query (investment channel)", get("E2_dual_query"))
if get("E2_dual_startup"):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.8))
    for i, (pre, lab) in enumerate([("E1_single_startup", "CreateStartup single (PDC)"), ("E2_dual_startup", "CreateStartup dual (gov., 2 endorsers)"),
                                    ("E1_single_invest", "MakeInvestment single (PDC)"), ("E2_dual_invest", "MakeInvestment dual (inv.)")]):
        line(a1, get(pre), lambda r: r["throughput"], lab, i, end_label=False)
        line(a2, get(pre), lambda r: 100 - succ_rate(r), lab, i, end_label=False)
    a1.set_xlabel("Offered load (TPS)"); a1.set_ylabel("Committed throughput (TPS)"); a1.set_title("Single vs dual channel", color=INK, loc="left")
    a2.set_xlabel("Offered load (TPS)"); a2.set_ylabel("Failed transactions (%)"); a2.set_title("Failure rate", color=INK, loc="left")
    a1.legend(fontsize=7); save(fig, "fig_e2_single_vs_dual.png")

# ---------------------------------------------------------------- E3
md.append("\n## E3 - Peer-count scaling (1/2/3 peers per org = 4/8/12 peers, 1 orderer)")
for p in (4, 8, 12):
    for wl in ("register", "token"): table(f"E3 {p} peers - {wl}", get(f"E3_p{p}_{wl}"))
    table(f"E3 {p} peers - query", get(f"E3_p{p}_query"))
pk = {wl: [(p, peak(get(f"E3_p{p}_{wl}"))) for p in (4, 8, 12) if get(f"E3_p{p}_{wl}")] for wl in ("register", "token", "query")}
if pk["token"]:
    md.append("\n### E3 summary - peak throughput by peer count\n\n| Peers | RegisterInvestor peak TPS | CreateTokenAccount peak TPS | Query TPS @2000 | Host mem peak (MB) |\n|---|---|---|---|---|")
    for p in (4, 8, 12):
        a = dict(pk["register"]).get(p); b = dict(pk["token"]).get(p); q = dict(pk["query"]).get(p)
        mem = max([r["resources"].get("host", {}).get("memUsedPeakMB", 0) for r in get(f"E3_p{p}_token")] or [0])
        md.append(f"| {p} | {a['throughput'] if a else '-'} | {b['throughput'] if b else '-'} | {q['throughput'] if q else '-'} | {mem} |")
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    for i, wl in enumerate(("register", "token")):
        xs = [p for p, _ in pk[wl]]; ys = [r["throughput"] for _, r in pk[wl]]
        ax.plot(xs, ys, color=C[i], marker=MK[i], label={"register": "RegisterInvestor", "token": "CreateTokenAccount"}[wl])
        for x, y in zip(xs, ys): ax.annotate(f"{y:g}", (x, y), xytext=(0, 6), textcoords="offset points", ha="center", fontsize=8, color=INK2)
    ax.set_xticks([4, 8, 12]); ax.set_xlabel("Total peers (4 orgs)"); ax.set_ylabel("Peak committed TPS"); ax.set_ylim(0, None)
    ax.set_title("Peer-count scaling (single host)", color=INK, loc="left"); ax.legend(fontsize=8); save(fig, "fig_e3_peers.png")

# ---------------------------------------------------------------- E4
md.append("\n## E4 - Ordering-service scaling (1/3/5 Raft orderers, 4 peers)")
for m in (1, 3, 5): table(f"E4 {m} orderer(s) - CreateTokenAccount", get(f"E4_o{m}_token"))
if get("E4_o1_token"):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.6))
    for i, m in enumerate((1, 3, 5)):
        line(a1, get(f"E4_o{m}_token"), lambda r: r["throughput"], f"{m} orderer{'s' if m > 1 else ''}", i)
        line(a2, get(f"E4_o{m}_token"), lambda r: r["latAvg"], f"{m} orderer{'s' if m > 1 else ''}", i)
    a1.set_xlabel("Offered load (TPS)"); a1.set_ylabel("Committed throughput (TPS)"); a1.set_title("Throughput vs Raft cluster size", color=INK, loc="left")
    a2.set_xlabel("Offered load (TPS)"); a2.set_ylabel("Average latency (s)"); a2.set_title("Latency", color=INK, loc="left")
    a1.legend(fontsize=8); save(fig, "fig_e4_orderers.png")

# ---------------------------------------------------------------- E5
md.append("\n## E5 - Number of required endorsers (OutOf(k, 4 orgs)), CreateTokenAccount")
for k in (1, 2, 3, 4): table(f"E5 k={k} endorsers", get(f"E5_e{k}_token"), [("Endorse-mismatch %", mm)])
if get("E5_e1_token"):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.6))
    for i, k in enumerate((1, 2, 3, 4)):
        line(a1, get(f"E5_e{k}_token"), lambda r: r["throughput"], f"{k} of 4", i)
        line(a2, get(f"E5_e{k}_token"), lambda r: 100.0 * r["errors"].get("ENDORSE_MISMATCH", 0) / max(r["submitted"], 1), f"{k} of 4", i)
    a1.set_xlabel("Offered load (TPS)"); a1.set_ylabel("Committed throughput (TPS)"); a1.set_title("Throughput vs endorsers required", color=INK, loc="left")
    a2.set_xlabel("Offered load (TPS)"); a2.set_ylabel("Rejected: endorsement mismatch (%)"); a2.set_title("Non-determinism (time.Now) failures", color=INK, loc="left")
    a1.legend(fontsize=8); save(fig, "fig_e5_endorsers.png")

# ---------------------------------------------------------------- E6
md.append("\n## E6 - Orderer batch configuration (BatchTimeout / MaxMessageCount), CreateTokenAccount")
bcfg = [("2s", 500), ("1s", 100), ("500ms", 50), ("250ms", 25)]
for bt, bs in bcfg: table(f"E6 batch {bt}/{bs}", get(f"E6_bt{bt}_bs{bs}_token"))
if get("E6_bt2s_bs500_token"):
    fig, ax = plt.subplots(figsize=(5.6, 3.6))
    for i, (bt, bs) in enumerate(bcfg): line(ax, get(f"E6_bt{bt}_bs{bs}_token"), lambda r: r["latAvg"], f"{bt}/{bs}", i)
    ax.set_xlabel("Offered load (TPS)"); ax.set_ylabel("Average latency (s)"); ax.set_title("Batch timeout / size vs latency", color=INK, loc="left")
    ax.legend(fontsize=8); save(fig, "fig_e6_batch.png")

# ---------------------------------------------------------------- resource breakdown figure
rows = get("E1_single_token") or get("E1_single_register")
if rows:
    roles = ["peer", "couchdb", "orderer", "chaincode", "loadgen"]
    fig, ax = plt.subplots(figsize=(6.4, 3.8))
    xs = [str(int(r["targetTps"])) for r in rows]; bottom = [0] * len(rows)
    for i, role in enumerate(roles):
        v = [cpu(r, role) for r in rows]
        ax.bar(xs, v, bottom=bottom, color=C[i], label=role, edgecolor="white", linewidth=2, width=0.62)
        bottom = [b + x for b, x in zip(bottom, v)]
    ax.axhline(400, color=INK2, ls=":", lw=1); ax.annotate("4 vCPU = 400%", (0, 405), color=INK2, fontsize=8)
    ax.set_xlabel("Offered load (TPS) - CreateTokenAccount"); ax.set_ylabel("Average CPU (% of one vCPU)")
    ax.set_title("CPU by component", color=INK, loc="left"); ax.legend(fontsize=8, ncol=5, loc="upper left", bbox_to_anchor=(0, -0.18))
    save(fig, "fig_resources_cpu.png")

# ---------------------------------------------------------------- security
sec = []
for f in sorted(glob.glob(os.path.join(RES, "security", "*.json"))):
    for r in json.load(open(f)): r["suite"] = os.path.basename(f)[:-5]; sec.append(r)
for f in glob.glob(os.path.join(RES, "bridge", "v3_tamper.json")):
    for r in json.load(open(f)):
        sec.append({"suite": "bridge_v3", "id": r["id"], "category": "Cross-channel bridge", "claim": r["test"], "attacker": "malicious relay / channel member",
                    "action": r["test"], "outcome": r["outcome"], "evidence": r["evidence"]})
if sec:
    md.append("\n## Security - attack simulation on the live network\n\n| Suite | ID | Category | Security property | Attacker | Attack | Outcome | Evidence |\n|---|---|---|---|---|---|---|---|")
    for r in sec:
        e = r["evidence"] if isinstance(r["evidence"], str) else json.dumps(r["evidence"])
        md.append(f"| {r['suite']} | {r['id']} | {r['category']} | {r['claim']} | {r['attacker']} | {r['action']} | **{r['outcome']}** | {e[:220].replace('|', '/')} |")

# ---------------------------------------------------------------- bridge
br = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(RES, "bridge", "v*_*.json"))) if "tamper" not in f]
if br:
    md.append("\n## Cross-channel synchronisation (governance -> investment)\n\n| Run | Offered TPS | Source committed | Relayed | Present on target | Missing | Source TPS | End-to-end TPS | Sync lag avg (s) | p50 | p95 | max | Idempotent replays |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for b in sorted(br, key=lambda b: (b["tag"].rsplit("_", 1)[0], b["tps"])):
        md.append(f"| {b['tag']} | {b['tps']} | {b['sourceCommitted']}/{b['submitted']} | {b['relayed']} | {b['targetPresent']} | {b['missing']} | {b['sourceThroughput']} | {b['endToEndThroughput']} | {b['syncLagAvg']} | {b['syncLagP50']} | {b['syncLagP95']} | {b['syncLagMax']} | {b['idempotentReplaysObserved']} |")
    series = [("v3_sync", "per-entry ApplySync"), ("v3batch_sync", "batched ApplySyncBatch (<=100)")]
    if any(b["tag"].startswith("v3_sync") for b in br):
        fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.6))
        for i, (pre, lab) in enumerate(series):
            rows = sorted([b for b in br if b["tag"].startswith(pre + "_")], key=lambda b: b["tps"])
            if not rows: continue
            xs = [b["tps"] for b in rows]
            a1.plot(xs, [b["syncLagAvg"] for b in rows], color=C[i], marker=MK[i], label=f"{lab} (avg)")
            a1.plot(xs, [b["syncLagP95"] for b in rows], ":", color=C[i], marker=MK[i], label=f"{lab} (p95)")
            a2.plot(xs, [b["endToEndThroughput"] for b in rows], color=C[i], marker=MK[i], label=lab)
        a2.plot([10, 150], [10, 150], ":", color=INK2, lw=1); a2.annotate("ideal", (100, 108), color=INK2, fontsize=8)
        a1.set_xlabel("Offered load on governance channel (TPS)"); a1.set_ylabel("Sync lag, source commit -> target commit (s)")
        a1.set_title("Cross-channel sync lag", color=INK, loc="left"); a1.set_ylim(0, None); a1.legend(fontsize=7)
        a2.set_xlabel("Offered load on governance channel (TPS)"); a2.set_ylabel("Records synced per second")
        a2.set_title("End-to-end sync throughput", color=INK, loc="left"); a2.set_ylim(0, None); a2.legend(fontsize=7)
        save(fig, "fig_bridge_lag.png")

open(os.path.join(RES, "RESULTS_TABLES.md"), "w").write("\n".join(md) + "\n")
if summary:
    with open(os.path.join(RES, "summary.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(summary[0].keys())); w.writeheader(); w.writerows(summary)
print(f"rounds={len(R)} security={len(sec)} bridge={len(br)} -> results/RESULTS_TABLES.md, results/figures/")
